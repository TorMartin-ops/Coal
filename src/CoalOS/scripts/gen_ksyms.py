#!/usr/bin/env python3
"""Build the kernel symbol table that backtraces use (debug kernel only).

  gen_ksyms.py --stub OUT.c             empty table for the first link
  gen_ksyms.py KERNEL.ELF OUT.c         table of the functions in KERNEL.ELF
  gen_ksyms.py --check A.ELF B.ELF      fail if a function moved between the two links

The table holds offsets from the start of the kernel text, sorted, plus a name blob.
"""
import subprocess
import sys


def functions(elf):
    out = subprocess.run(["nm", "-n", "-S", "--defined-only", elf], check=True, stdout=subprocess.PIPE,
                         universal_newlines=True).stdout
    syms = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[2] in "Tt":
            syms.append((int(parts[0], 16), int(parts[1], 16), parts[3]))
        elif len(parts) == 3 and parts[1] in "Tt":          # assembly labels carry no size
            syms.append((int(parts[0], 16), 0, parts[2]))
    return syms


def text_start(elf):
    out = subprocess.run(["nm", elf], check=True, stdout=subprocess.PIPE, universal_newlines=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] == "_kernel_text_start":
            return int(parts[0], 16)
    raise SystemExit("no _kernel_text_start")


def write(path, syms, base):
    names, offs = bytearray(), []
    for addr, size, name in syms:
        offs.append(len(names))
        names += name.encode() + b"\0"
    with open(path, "w") as f:
        f.write("/* Generated by scripts/gen_ksyms.py. */\n#include <libc/stdint.h>\n")
        f.write("const uint32_t ksym_count = %d;\n" % len(syms))
        f.write("const uint32_t ksym_addr[%d] = {%s};\n" % (max(len(syms), 1), ",".join("%#x" % (a - base) for a, _, _ in syms) or "0"))
        f.write("const uint32_t ksym_size[%d] = {%s};\n" % (max(len(syms), 1), ",".join("%d" % s for _, s, _ in syms) or "0"))
        f.write("const uint32_t ksym_name[%d] = {%s};\n" % (max(len(syms), 1), ",".join("%d" % o for o in offs) or "0"))
        f.write("const char ksym_names[%d] = {%s};\n" % (max(len(names), 1), ",".join(str(b) for b in names) or "0"))


def main(argv):
    if argv[:1] == ["--stub"]:
        write(argv[1], [], 0)
    elif argv[:1] == ["--check"]:
        a, b = functions(argv[1]), functions(argv[2])
        a = {n: x for x, _, n in a if not n.startswith("ksym")}
        b = {n: x for x, _, n in b if not n.startswith("ksym")}
        moved = [n for n in a if b.get(n) != a[n]]
        if moved:
            raise SystemExit("symbol table moved functions: " + ", ".join(moved[:8]))
    else:
        write(argv[1], functions(argv[0]), text_start(argv[0]))


if __name__ == "__main__":
    main(sys.argv[1:])
