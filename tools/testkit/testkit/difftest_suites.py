"""The syscall differential corpus, the file-operation fuzzer and LTP as tests (tools/difftest).

The corpus and the fuzzer run inside one guest each, started by init; the host runs the same programs and compares the
traces. Coal does not match Linux everywhere yet: baselines/difftest_known_divergences.txt and
baselines/difftest_fuzz_known.txt list the divergences that are expected. A divergence outside the list is a
regression, a listed one that disappeared makes the list stale; both fail the test. LTP is a long host-driven test
(it boots Coal through the gateway in batches) against baselines/ltp_known_failures.txt in the same way.

Regenerate a baseline after a deliberate change with COAL_TESTKIT_UPDATE_BASELINES=1 (the test then passes and rewrites it).
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

from .model import Test
from .qemu import GuestSpec

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
DT = os.path.join(REPO, "tools", "difftest")
BASELINES = os.path.join(os.path.dirname(HERE), "baselines")
BIN = os.path.join(REPO, "build", "testkit-difftest", "bin")
LTP_DIR = os.path.join(REPO, "build", "difftest-external", "ltp")
KLOG = re.compile(r"^\[\s*\d+\.\d{3}\] \[\w+\s*\] .*\n", re.M)
FUZZ_SEEDS, FUZZ_LENGTH = 40, 20

CORPUS_DRIVER = """cd /
for p in $(ls /tmp/dt); do
    echo "@@PROG $p"
    rm -rf /tmp/work; mkdir /tmp/work; cd /tmp/work
    /tmp/dt/$p < /dev/null 2> /dev/null
    printf '\\n@@EXIT %d\\n' $?
    cd /
done
"""
FUZZ_DRIVER = """cd /
n=1
while [ -f /tmp/fz/$n.txt ]; do
    echo "@@PROG $n"
    /tmp/fz/fsops /tmp/fz/$n.txt /tmp/dt_fz$n < /dev/null 2> /dev/null
    printf '\\n@@EXIT %d\\n' $?
    n=$((n + 1))
done
"""
BLOCK = re.compile(r"@@PROG (\S+)\n(.*?)\n@@EXIT (\d+)\n", re.S)


def _difftest():
    if DT not in sys.path:
        sys.path.insert(0, DT)
    import difftest
    return difftest


def _baseline(name):
    try:
        with open(os.path.join(BASELINES, name)) as f:
            return {line.rstrip("\n") for line in f if line.strip() and not line.startswith("#")}
    except OSError:
        return set()


def _compare(name, observed, header, ignore=()):
    """None when `observed` is the baseline; otherwise what is new or stale. Rewrites the baseline on request."""
    if os.environ.get("COAL_TESTKIT_UPDATE_BASELINES"):
        with open(os.path.join(BASELINES, name), "w") as f:
            f.write("# %s\n" % header + "".join(k + "\n" for k in sorted(observed)))
        return None
    known = _baseline(name) - set(ignore)
    observed = observed - set(ignore)
    new, stale = sorted(observed - known), sorted(known - observed)
    if new:
        return "%d new divergences: %s" % (len(new), "; ".join(new[:6]))
    if stale:
        return "baseline is stale, %d no longer happen: %s" % (len(stale), "; ".join(stale[:6]))
    return None


def _blocks(text):
    text = KLOG.sub("", text.replace("\r", ""))
    return {m.group(1): (m.group(2), int(m.group(3))) for m in BLOCK.finditer(text)}


class Files(dict):
    """Guest files built on first use, so listing the registry does not compile anything."""

    def __init__(self, make):
        super().__init__()
        self.make, self.done = make, False

    def _fill(self):
        if not self.done:
            self.done = True
            self.update(self.make())

    def __bool__(self):
        return True

    def __iter__(self):
        self._fill()
        return super().__iter__()

    def items(self):
        self._fill()
        return super().items()


def _read(path):
    with open(path, "rb") as f:
        return f.read()


def _corpus_files():
    d = _difftest()
    names = d.programs()
    d.build(names, BIN)
    files = {"/tmp/dt/" + n: _read(os.path.join(BIN, n)) for n in names}
    files["/tmp/dtrun.sh"] = CORPUS_DRIVER.encode()
    return files


def check_corpus(text):
    d = _difftest()
    got, observed = _blocks(text), set()
    for n in d.programs():
        host = d.run_host(os.path.join(BIN, n))
        if n not in got:
            observed.add("%s: did not complete" % n)
            continue
        out, code = got[n]
        guest = {"stdout": out + "\n", "exit_code": code, "signal": None, "timed_out": False}
        if code > 128:
            guest.update(exit_code=None, signal=code - 128)
        divs, _ = d.compare(host, guest)
        for x in divs:
            observed.add("%s: %s => %s" % (n, x["host"] or "-", x["coal"] or "-"))
    return _compare("difftest_known_divergences.txt", observed,
                    "difftest corpus: program: Linux line => Coal line. Generated by COAL_TESTKIT_UPDATE_BASELINES=1.")


def _fuzz_files():
    d = _difftest()
    import fuzz
    exe = os.path.join(BIN, "fsops")
    os.makedirs(BIN, exist_ok=True)
    subprocess.run(d.CC + ["-I" + d.CORPUS, "-o", exe, os.path.join(d.CORPUS, "fsops.c")], check=True)
    files = {"/tmp/fz/fsops": _read(exe), "/tmp/fzrun.sh": FUZZ_DRIVER.encode()}
    for seed in range(1, FUZZ_SEEDS + 1):
        files["/tmp/fz/%d.txt" % seed] = ("\n".join(fuzz.gen(seed, FUZZ_LENGTH)) + "\n").encode()
    return files


def check_fuzz(text):
    d = _difftest()
    import fuzz
    got, observed = _blocks(text), set()
    exe = os.path.join(BIN, "fsops")
    tmp = tempfile.mkdtemp(prefix="fuzzseed-")
    try:
        for seed in range(1, FUZZ_SEEDS + 1):
            script = os.path.join(tmp, "s.txt")
            with open(script, "w") as f:
                f.write("\n".join(fuzz.gen(seed, FUZZ_LENGTH)) + "\n")
            host = d.run_host(exe, args=[script, "/tmp/dt_fz%d" % seed])["stdout"]
            if str(seed) not in got:
                observed.add("seed %d: did not complete" % seed)
                continue
            div = fuzz.divergences(host, got[str(seed)][0] + "\n")
            if div:                                  # later lines follow from the first one's state
                observed.add("seed %d line %d: %s => %s" % (seed, div[0][0], div[0][3], div[0][4]))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return _compare("difftest_fuzz_known.txt", observed,
                    "fuzzer seeds 1-%d, length %d: first divergence of each seed. Generated by COAL_TESTKIT_UPDATE_BASELINES=1."
                    % (FUZZ_SEEDS, FUZZ_LENGTH))


LTP_LINE = re.compile(r"^(\S+/\S+)\s+coal=(\w+)\s+host=(\w+)\s*$", re.M)


def check_ltp(text):
    rows = LTP_LINE.findall(text)
    if not rows:
        return "no test results in the output"
    total = sum(len(files) for _, _, files in os.walk(LTP_DIR))
    if total and len({r[0] for r in rows}) < total:
        return "only %d of %d tests reported a result" % (len({r[0] for r in rows}), total)
    observed = {name for name, coal, host in rows if host == "pass" and coal != "pass"}
    flaky = {name for name, coal, host in rows if coal == "flaky"} | _baseline("ltp_flaky.txt")   # no verdict: neither new nor stale
    return _compare("ltp_known_failures.txt", observed,
                    "LTP tests that pass on Linux and do not pass in Coal. Generated by COAL_TESTKIT_UPDATE_BASELINES=1.", flaky)


def _guest_test(name, driver, make, check, cost):
    spec = GuestSpec(argv=["/bin/sh", driver], files=Files(make), budget_s=600)
    return Test("difftest", name, guest=spec, deterministic=True, cost_s=cost, tags=("guest", "difftest"),
                needs=("qemu", "mtools", "musl-gcc"), count=re.compile(r"(@@PROG) \S+"), check=check)


def tests():
    from .suites import host
    ltp = host("difftest", "ltp", ["tools/difftest/external/ltp.py", "--ensure-built", "--ext", "{ltp}",
                                    "--build-dir", "{build}", "--batch", "1"], 6000, tags=("long", "host-io", "ltp"), qemu=True,
               count=re.compile(r"^(\S+/\S+)\s+coal=", re.M), check=check_ltp, needs=("musl-gcc",))
    ltp.cmd = [a.replace("{ltp}", os.path.dirname(LTP_DIR)) for a in ltp.cmd]
    return [_guest_test("corpus", "/tmp/dtrun.sh", _corpus_files, check_corpus, 20),
            _guest_test("fuzz", "/tmp/fzrun.sh", _fuzz_files, check_fuzz, 10), ltp]
